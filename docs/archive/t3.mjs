import { chromium } from 'playwright-core';
const b = await chromium.launch({executablePath:'/opt/pw-browsers/chromium'}); const p = await b.newPage();
const errs=[]; p.on('pageerror',e=>errs.push(String(e)));
const fs = await import('fs');
const html = fs.readFileSync('/home/claude/design-docs.html','utf8');
await p.setContent(`<iframe sandbox="allow-scripts" srcdoc="${html.replace(/"/g,'&quot;')}" style="width:1200px;height:900px;border:0"></iframe>`);
await p.waitForTimeout(2500);
const f = p.frames()[1];
const r = await f.evaluate(()=>({secs:document.querySelectorAll('section.doc.active').length, nav:document.querySelectorAll('nav a, .nav a, [data-doc]').length, title:document.title}));
console.log('errors:', errs.length? errs : 'none'); console.log(JSON.stringify(r));
await b.close();
